        private unsafe void ApplyAllPatches()
        {
            try
            {
                // Get the base address of the main executable
                var mainModule = Process.GetCurrentProcess().MainModule;
                if (mainModule == null)
                {
                    _logger.WriteLine("[BlueMage] Error: Could not get main module");
                    return;
                }

                var baseAddress = mainModule.BaseAddress;
                int successfulPatches = 0;
                int failedPatches = 0;
                int delayedPatches = 0;

                _logger.WriteLine($"[BlueMage] Starting Blue Mage mod - applying {_memoryPatches.Length} patches");
                _logger.WriteLine($"[BlueMage] Base address: {baseAddress:X}");

                // Apply immediate patches and collect delayed patches
                List<MemoryPatch> delayedPatchList = new List<MemoryPatch>();

                foreach (var patch in _memoryPatches)
                {
                    if (patch.DelayPatch)
                    {
                        delayedPatchList.Add(patch);
                        delayedPatches++;
                        _logger.WriteLine($"[BlueMage] Deferring '{patch.Description}' for delayed application");
                    }
                    else
                    {
                        if (ApplySinglePatch(baseAddress, patch))
                        {
                            successfulPatches++;
                        }
                        else
                        {
                            failedPatches++;
                        }
                    }
                }

                // Log initial results
                _logger.WriteLine($"[BlueMage] Immediate patching complete!");
                _logger.WriteLine($"[BlueMage] Successful: {successfulPatches}/{_memoryPatches.Length - delayedPatches}");
                if (failedPatches > 0)
                {
                    _logger.WriteLine($"[BlueMage] Failed: {failedPatches}/{_memoryPatches.Length - delayedPatches}");
                }
                if (delayedPatches > 0)
                {
                    _logger.WriteLine($"[BlueMage] Delayed patches scheduled: {delayedPatches}");
                }

                // Apply delayed patches after 45 seconds
                if (delayedPatchList.Count > 0)
                {
                    Task.Delay(45000).ContinueWith(_ =>
                    {
                        _logger.WriteLine($"[BlueMage] Applying {delayedPatchList.Count} delayed patches...");
                        int delayedSuccess = 0;
                        int delayedFailed = 0;

                        foreach (var patch in delayedPatchList)
                        {
                            if (ApplySinglePatch(baseAddress, patch))
                            {
                                delayedSuccess++;
                            }
                            else
                            {
                                delayedFailed++;
                            }
                        }

                        _logger.WriteLine($"[BlueMage] Delayed patching complete!");
                        _logger.WriteLine($"[BlueMage] Delayed successful: {delayedSuccess}/{delayedPatchList.Count}");
                        if (delayedFailed > 0)
                        {
                            _logger.WriteLine($"[BlueMage] Delayed failed: {delayedFailed}/{delayedPatchList.Count}");
                        }
                    });
                }
            }
            catch (Exception ex)
            {
                _logger.WriteLine($"[BlueMage] Critical error during patching: {ex.Message}");
            }
        }

        private unsafe bool ApplySinglePatch(IntPtr baseAddress, MemoryPatch patch)
        {
            try
            {
                var targetAddress = IntPtr.Add(baseAddress, patch.Offset);
                byte* ptr = (byte*)targetAddress.ToPointer();

                // Log patch attempt
                _logger.WriteLine($"[BlueMage] Applying '{patch.Description}' at {targetAddress:X} ({patch.Data.Length} bytes)");

                // Make memory writable
                uint oldProtect;
                if (!VirtualProtect(targetAddress, (UIntPtr)patch.Data.Length,
                    MemoryProtection.ExecuteReadWrite, out oldProtect))
                {
                    _logger.WriteLine($"[BlueMage] Failed to change memory protection for '{patch.Description}'");
                    return false;
                }

                // Write the bytes
                for (int i = 0; i < patch.Data.Length; i++)
                {
                    ptr[i] = patch.Data[i];
                }

                // Restore original protection
                uint temp;
                VirtualProtect(targetAddress, (UIntPtr)patch.Data.Length,
                    (MemoryProtection)oldProtect, out temp);

                // Verify the patch
                for (int i = 0; i < patch.Data.Length; i++)
                {
                    if (ptr[i] != patch.Data[i])
                    {
                        _logger.WriteLine($"[BlueMage] Verification failed for '{patch.Description}' at byte {i}");
                        return false;
                    }
                }

                _logger.WriteLine($"[BlueMage] Successfully applied '{patch.Description}'");
                return true;
            }
            catch (Exception ex)
            {
                _logger.WriteLine($"[BlueMage] Exception while applying '{patch.Description}': {ex.Message}");
                return false;
            }
        }

